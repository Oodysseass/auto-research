#!/usr/bin/env python3
"""Automatic token budgets for the research workflow. Stdlib only. Budgets are never a human decision.

Usage:
  budgets.py get <stage-type>            the budget for one brief of this stage type (calibrated, else default)
  budgets.py log --root R --stage-type T --brief B --role ROLE --tokens N [--session S]
                                         append one dispatch to R/.work/usage.tsv and to the global log
  budgets.py recalibrate                 rewrite budgets.json from the global log

Files:
  skills/model-routing/budgets.default.json   defaults, tracked
  skills/model-routing/budgets.json           calibrated values, git-ignored ($RW_BUDGETS overrides the path)
  ~/.claude/rw-usage.tsv                      global log across projects ($RW_USAGE_GLOBAL overrides the path)

Recalibration: per stage type, the total tokens of each brief in the global log; with at least 3 briefs,
budget = 90th percentile x 1.25, rounded up to 10k. Fewer briefs: the default.
"""
import argparse
import math
import os
import sys
from datetime import datetime
from pathlib import Path

ROUTING = Path(__file__).resolve().parent.parent / "skills" / "model-routing"
DEFAULTS = ROUTING / "budgets.default.json"
HEADER = "time\tsession\tstage_type\tbrief\trole\ttokens\n"
GLOBAL_HEADER = "time\tproject\tstage_type\tbrief\trole\ttokens\n"
MIN_SAMPLES = 3


def calibrated_path():
    return Path(os.environ.get("RW_BUDGETS", ROUTING / "budgets.json"))


def global_path():
    return Path(os.environ.get("RW_USAGE_GLOBAL", Path.home() / ".claude" / "rw-usage.tsv"))


def _load(p):
    import json
    try:
        return {k: v for k, v in json.loads(Path(p).read_text()).items() if not k.startswith("_")}
    except (OSError, ValueError):
        return {}


def get(stage_type):
    cal, dfl = _load(calibrated_path()), _load(DEFAULTS)
    key = stage_type if stage_type in dfl or stage_type in cal else "other"
    return int(cal.get(key) or dfl.get(key) or dfl.get("other", 300000))


def _append(p, header, row):
    p = Path(p)
    p.parent.mkdir(parents=True, exist_ok=True)
    new = not p.is_file() or p.stat().st_size == 0
    with p.open("a") as f:
        if new:
            f.write(header)
        f.write("\t".join(str(x).replace("\t", " ") for x in row) + "\n")


def log(root, stage_type, brief, role, tokens, session="-"):
    t = datetime.now().strftime("%Y-%m-%dT%H:%M")
    _append(Path(root) / ".work" / "usage.tsv", HEADER, [t, session, stage_type, brief, role, int(tokens)])
    _append(global_path(), GLOBAL_HEADER, [t, Path(root).resolve(), stage_type, brief, role, int(tokens)])


def percentile(xs, q):
    xs = sorted(xs)
    k = (len(xs) - 1) * q
    lo, hi = math.floor(k), math.ceil(k)
    return xs[lo] + (xs[hi] - xs[lo]) * (k - lo)


def recalibrate():
    import json
    totals = {}
    p = global_path()
    if p.is_file():
        for line in p.read_text().splitlines()[1:]:
            c = line.split("\t")
            if len(c) >= 6 and c[5].strip().isdigit():
                key = (c[2], c[1], c[3])
                totals[key] = totals.get(key, 0) + int(c[5])
    per_type = {}
    for (st, _, _), n in totals.items():
        per_type.setdefault(st, []).append(n)
    dfl = _load(DEFAULTS)
    out = {"_doc": "Generated by budgets.py recalibrate. Do not edit."}
    for st in sorted(set(dfl) | set(per_type)):
        xs = per_type.get(st, [])
        if len(xs) >= MIN_SAMPLES:
            out[st] = int(math.ceil(percentile(xs, 0.9) * 1.25 / 10000) * 10000)
        elif st in dfl:
            out[st] = dfl[st]
    calibrated_path().write_text(json.dumps(out, indent=2) + "\n")
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("get"); p.add_argument("stage_type")
    p = sub.add_parser("log")
    for k in ("--root", "--stage-type", "--brief", "--role", "--tokens"):
        p.add_argument(k, required=True)
    p.add_argument("--session", default="-")
    sub.add_parser("recalibrate")
    a = ap.parse_args(argv)
    if a.cmd == "get":
        print(get(a.stage_type))
    elif a.cmd == "log":
        log(a.root, a.stage_type, a.brief, a.role, a.tokens, a.session)
    else:
        out = recalibrate()
        print(f"budgets.json: {len(out) - 1} stage types")
    return 0


if __name__ == "__main__":
    sys.exit(main())
